/**
 * Enqueue Google Fonts, 5-way CSS stylesheets, and modular JS modules.
 */
function grantrade_enqueue_assets()
{
	$theme_uri = get_template_directory_uri();
	$ver = GRANTRADE_VERSION;

	// Typography (Marcellus & Archivo)
	wp_enqueue_style(
		'grantrade-fonts',
		'https://fonts.googleapis.com/css2?family=Marcellus&family=Archivo:ital,wght@0,400;0,500;0,600;0,700;1,400&display=swap',
		array(),
		null
	);

	// 5-Way CSS Architecture
	wp_enqueue_style('grantrade-base', $theme_uri . '/css/base.css', array('grantrade-fonts'), $ver);
	wp_enqueue_style('grantrade-layout', $theme_uri . '/css/layout.css', array('grantrade-base'), $ver);
	wp_enqueue_style('grantrade-components', $theme_uri . '/css/components.css', array('grantrade-layout'), $ver);
	wp_enqueue_style('grantrade-pages', $theme_uri . '/css/pages.css', array('grantrade-components'), $ver);
	wp_enqueue_style('grantrade-responsive', $theme_uri . '/css/responsive.css', array('grantrade-pages'), $ver);
	wp_enqueue_style('grantrade-theme-style', get_stylesheet_uri(), array('grantrade-responsive'), $ver);

	// Catalog & WordPress environment adapter
	wp_enqueue_script('grantrade-catalog-data', $theme_uri . '/js/stone-catalog-data.js', array(), $ver, true);
	wp_enqueue_script('grantrade-wp-compat', $theme_uri . '/js/wp-compat.js', array('grantrade-catalog-data'), $ver, true);

	$catalog_mode = grantrade_get_option('gt_catalog_mode', 'wp_only');
	wp_localize_script(
		'grantrade-wp-compat',
		'GRAN_TRADE_ENV',
		array(
			'isWordPress' => true,
			'themeUrl' => $theme_uri,
			'homeUrl' => home_url('/'),
			'ajaxUrl' => admin_url('admin-ajax.php'),
			'nonce' => wp_create_nonce('grantrade_inquiry_nonce'),
			'salesEmail' => grantrade_get_option('gt_sales_email', 'sales.grantrade@gmail.com'),
			'inquiryEmail' => grantrade_get_option('gt_inquiry_email', 'grantrade@gmail.com'),
			'replaceBuiltinCatalog' => ('wp_only' === $catalog_mode),
			'wpStones' => grantrade_get_wp_stones(),
			'customColors' => get_option('gt_custom_color_swatches', array()),
			'pages' => array(
				'home' => grantrade_get_page_url('home'),
				'about' => grantrade_get_page_url('about'),
				'collections' => grantrade_get_page_url('collections'),
				'showroom' => grantrade_get_page_url('showroom'),
				'contact' => grantrade_get_page_url('contact'),
				'slab' => grantrade_get_page_url('slab'),
			),
		)
	);

	// Core navigation & saved slabs drawer
	wp_enqueue_script('grantrade-nav', $theme_uri . '/js/nav.js', array('grantrade-wp-compat'), $ver, true);
	wp_enqueue_script('grantrade-favorites', $theme_uri . '/js/favorites.js', array('grantrade-wp-compat', 'grantrade-nav'), $ver, true);

	// Page-specific modules
	if (is_front_page()) {
		wp_enqueue_script('grantrade-viewer', $theme_uri . '/js/viewer.js', array('grantrade-wp-compat'), $ver, true);
		wp_enqueue_script('grantrade-stone-types', $theme_uri . '/js/stone-types.js', array('grantrade-wp-compat'), $ver, true);
		wp_enqueue_script('grantrade-homepage-loader', $theme_uri . '/js/homepage-loader.js', array('grantrade-wp-compat'), $ver, true);
	}

	if (is_page_template('page-collections.php') || is_page('collections') || is_tax('gt_family')) {
		wp_enqueue_script('grantrade-tabs', $theme_uri . '/js/tabs.js', array('grantrade-wp-compat'), $ver, true);
		wp_enqueue_script('grantrade-filters', $theme_uri . '/js/filters.js', array('grantrade-wp-compat', 'grantrade-favorites', 'grantrade-tabs'), $ver, true);
	}

	if (is_page_template('page-slab.php') || is_page('slab') || is_singular('gt_slab')) {
		wp_enqueue_script('grantrade-slab-detail', $theme_uri . '/js/slab-detail.js', array('grantrade-wp-compat', 'grantrade-favorites'), $ver, true);
	}

	if (is_page_template('page-contact.php') || is_page(array('contact', 'contact-us'))) {
		wp_enqueue_script('grantrade-contact-guard', $theme_uri . '/js/contact-guard.js', array(), $ver, false);
	}
}
add_action('wp_enqueue_scripts', 'grantrade_enqueue_assets');

/**
 * Add `.nav-link` class to primary menu anchors generated by wp_nav_menu().
 */
function grantrade_nav_link_attributes($atts, $item, $args)
{
	if (isset($args->theme_location) && 'primary' === $args->theme_location) {
		$existing = isset($atts['class']) ? $atts['class'] . ' ' : '';
		$atts['class'] = trim($existing . 'nav-link');
	}
	return $atts;
}
add_filter('nav_menu_link_attributes', 'grantrade_nav_link_attributes', 10, 3);

/**
 * Default fallback menu when no custom WordPress menu is assigned to `primary`.
 */
function grantrade_fallback_menu()
{
	$items = array(
		array('slug' => 'home', 'label' => __('Home', 'grantrade')),
		array('slug' => 'about', 'label' => __('About Us', 'grantrade')),
		array('slug' => 'collections', 'label' => __('Collections', 'grantrade')),
		array('slug' => 'showroom', 'label' => __('Showroom & Yard', 'grantrade')),
		array('slug' => 'contact', 'label' => __('Contact Us', 'grantrade')),
	);

	echo '<ul class="nav-links">';
	foreach ($items as $item) {
		$url = grantrade_get_page_url($item['slug']);
		printf(
			'<li><a href="%s" class="nav-link">%s</a></li>',
			esc_url($url),
			esc_html($item['label'])
		);
	}
	echo '</ul>';
}

/**
 * Enqueue WP Admin styles, media library picker, built-in catalog data, and CodeMirror editors.
 */
function grantrade_enqueue_admin_assets( $hook ) {
	$screen     = function_exists( 'get_current_screen' ) ? get_current_screen() : null;
	$post_type  = $screen ? (string) $screen->post_type : '';
	$is_gt_page = false !== strpos( (string) $hook, 'grantrade-' );
	$is_gt_cpt  = in_array( $post_type, array( 'page', 'gt_slab', 'gt_inquiry' ), true );

	if ( ! $is_gt_page && ! $is_gt_cpt ) {
		return;
	}

	$theme_uri = get_template_directory_uri();
	$ver       = GRANTRADE_VERSION;

	wp_enqueue_style( 'grantrade-admin-css', $theme_uri . '/inc/admin-assets/admin.css', array(), $ver );

	if ( in_array( $hook, array( 'post.php', 'post-new.php' ), true ) && in_array( $post_type, array( 'page', 'gt_slab' ), true ) ) {
		wp_enqueue_media();
	}

	if ( false !== strpos( (string) $hook, 'grantrade-admin' ) ) {
		wp_enqueue_script( 'grantrade-catalog-data', $theme_uri . '/js/stone-catalog-data.js', array(), $ver, false );
	}

	$code_editors = array();
	if ( false !== strpos( (string) $hook, 'grantrade-file-manager' ) || false !== strpos( (string) $hook, 'grantrade-custom-code' ) ) {
		$modes = array(
			'css'     => 'text/css',
			'js'      => 'application/javascript',
			'html'    => 'text/html',
			'php'     => 'application/x-httpd-php',
			'default' => 'text/plain',
		);
		foreach ( $modes as $key => $mime ) {
			$settings = wp_enqueue_code_editor( array( 'type' => $mime ) );
			if ( false !== $settings ) {
				$code_editors[ $key ] = $settings;
			}
		}
	}

	wp_enqueue_script( 'grantrade-admin-js', $theme_uri . '/inc/admin-assets/admin.js', array( 'jquery' ), $ver, true );
	wp_localize_script(
		'grantrade-admin-js',
		'grantradeAdminData',
		array(
			'codeEditors' => $code_editors,
		)
	);
}
add_action( 'admin_enqueue_scripts', 'grantrade_enqueue_admin_assets' );

/**
 * Register Elementor Theme Builder core locations when Elementor Pro is active.
 */
function grantrade_register_elementor_locations( $elementor_theme_manager ) {
	if ( is_object( $elementor_theme_manager ) && method_exists( $elementor_theme_manager, 'register_all_core_location' ) ) {
		$elementor_theme_manager->register_all_core_location();
	}
}
add_action( 'elementor/theme/register_locations', 'grantrade_register_elementor_locations' );

/**
 * Ensure Elementor supports Pages, Posts, and Stone Slabs (`gt_slab`) out of the box.
 */
function grantrade_ensure_elementor_cpt_support() {
	if ( ! defined( 'ELEMENTOR_VERSION' ) ) {
		return;
	}
	$supported = (array) get_option( 'elementor_cpt_support', array( 'page', 'post' ) );
	$needed    = array( 'page', 'post', 'gt_slab' );
	$merged    = array_values( array_unique( array_merge( $supported, $needed ) ) );
	if ( $merged !== $supported ) {
		update_option( 'elementor_cpt_support', $merged );
	}
}
add_action( 'init', 'grantrade_ensure_elementor_cpt_support', 30 );



